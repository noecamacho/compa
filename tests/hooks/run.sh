#!/bin/sh
# Runs the commit-message checker and the agent PreToolUse hook against passing and failing cases.
# Usage: tests/hooks/run.sh   (exit 0 when every case behaves as expected)
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
CHECKER="$ROOT/scripts/check-commit-message.sh"
HOOK="$ROOT/scripts/hooks/agent-pretooluse.sh"
PASS=0
FAIL=0
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

record() {
  [ "$1" = "$2" ] && { PASS=$((PASS + 1)); printf 'ok   %s\n' "$3"; return 0; }
  FAIL=$((FAIL + 1)); printf 'FAIL %s (expected exit %s, got %s)\n' "$3" "$2" "$1"
}

expect_message() {
  printf '%b' "$2" > "$TMP/msg"
  "$CHECKER" "$TMP/msg" >/dev/null 2>&1
  record $? "$1" "checker: $3"
}

expect_hook() {
  printf '%s' "$2" | "$HOOK" >/dev/null 2>&1
  record $? "$1" "hook: $3"
}

json_command() {
  jq -cn --arg c "$1" '{tool_name:"Bash",tool_input:{command:$c}}'
}

heredoc_commit() {
  printf 'git commit -m "$(cat <<'"'"'EOF'"'"'\n%b\nEOF\n)"' "$1"
}

expect_message 0 'feat(api): add idempotent connection endpoint\n\nWhy: the plan requires it.\n' 'valid feat with scope and body'
expect_message 0 'docs: ingest build plan into wiki' 'valid docs without scope'
expect_message 0 'feat(api)!: drop legacy handle format\n\nBREAKING CHANGE: handles are lower-case.\n' 'valid breaking change'
expect_message 0 'Merge branch feat/x into main' 'git-generated merge subject'
expect_message 0 'fix(ui): keep de-duplicated list stable' 'english subject containing "de" inside a word'
expect_message 0 'docs(tooling): describe codex and claude hook setup' 'tool names in subject are not attribution'
expect_message 1 'Added the profile form' 'missing type'
expect_message 1 'feat: ' 'empty subject after type'
expect_message 1 'feat: add a very long subject line that keeps going and going well past the limit of 72' 'subject longer than 72'
expect_message 1 'feat: add form.' 'subject ending with period'
expect_message 1 'feat: add form\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n' 'AI co-author trailer'
expect_message 1 'feat: add form\n\n🤖 Generated with Claude Code\n' 'AI generated line'
expect_message 1 'feat: add form\n\nWritten with help from ChatGPT.\n' 'AI assistance line'
expect_message 1 'feat: agrega formulario de perfil' 'spanish subject'
expect_message 1 'fix: corrige validación' 'spanish subject with accent word'

expect_hook 0 "$(json_command 'git commit -m "feat(wiki): add glossary"')" 'allows valid inline message'
expect_message 0 'docs: document files generated by the codex hook' 'tool name after a verb is not attribution'
expect_message 0 'fix(ui): show cursor\n\nMade the cursor visible on focus.\n' 'english body with "made" is not attribution'
expect_message 1 'feat: add form\n\nCo-authored-by: aider (gpt-4) <noreply@aider.chat>\n' 'aider co-author trailer'
expect_message 1 'feat: add form\n\nAI-generated with care.\n' 'AI-generated line'
expect_message 0 'Merge remote-tracking branch origin/feat/COMPA-12-profile-form-with-a-long-name into main' 'long git-generated merge subject'
expect_message 1 'feat: add AÑO field' 'upper-case spanish letter'
expect_message 0 'docs: add notes\n\n# ------------------------ >8 ------------------------\n+Generated with Claude Code\n' 'verbose diff after scissors is ignored'
expect_hook 2 "$(json_command 'git commit -m "add glossary"')" 'blocks message without type'
expect_hook 2 "$(json_command "$(heredoc_commit 'feat: add glossary\n\nCo-Authored-By: Claude <noreply@anthropic.com>')")" 'blocks heredoc message with AI trailer'
expect_hook 0 "$(json_command "$(heredoc_commit 'feat: add glossary\n\nExplains the terms used in the wiki.')")" 'allows heredoc message with body'
expect_hook 0 "$(json_command 'git status')" 'ignores non-commit commands'
expect_hook 0 "$(json_command 'git commit')" 'allows editor commit (commit-msg hook checks it later)'
expect_hook 0 "$(json_command 'git commit --amend --no-edit')" 'allows amend without message change'
expect_hook 2 "$(json_command 'cd app && git commit -am "arregla el bug"')" 'blocks spanish subject after cd'
expect_hook 0 "$(json_command 'git commit -m "feat: add x" -m "Why: the plan requires it."')" 'leaves several -m flags to commit-msg'
expect_hook 0 "$(json_command 'echo "run git commit -m wip"')" 'ignores git commit mentioned inside another command'
expect_hook 2 "$(json_command 'git -C app commit -m "bad subject"')" 'blocks commit with a -C global option'
expect_hook 2 "$(json_command 'git -c user.name=x commit -m "bad subject"')" 'blocks commit with a -c global option'
expect_hook 0 "$(json_command 'git commit -m "feat: add x" && echo done.')" 'ignores shell text after the quoted message'
expect_hook 2 "$(json_command '(git commit -m "bad subject")')" 'blocks commit inside a subshell'

printf '\n%s passed, %s failed\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
